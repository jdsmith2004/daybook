#!/usr/bin/env node
/*
 * Builds packages/core/src/legacy/core.js from legacy/index.html.
 *
 * The single-file app (legacy/index.html) is the source of truth while the new app is built. Its pure parts (the data model,
 * counting, run saves, step down, points, badges, quests, the emblem SVG, the onboarding answers, and the lesson content) are
 * copied here verbatim, so the new app runs exactly the same rules. Nothing that touches the DOM or storage is copied.
 *
 * Run it again whenever legacy/index.html changes:  npm run extract
 * The golden tests in packages/core check the result against the legacy app itself.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as acorn from 'acorn';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'legacy/index.html'), 'utf8');
const lines = html.split('\n');

const at = (re, from = 0) => {
  for (let i = from; i < lines.length; i++) if (re.test(lines[i])) return i;
  throw new Error('marker not found: ' + re);
};
const slice = (a, b) => lines.slice(a, b).join('\n');

/* the slices, each between two markers in the legacy file */
const logicA = at(/^\/\* ===== LOGIC: pure functions/);
const logicB = at(/^\/\* ===== STORE:/, logicA);
const emA = at(/^\/\* ===== EMBLEM:/);
const emB = at(/^function sunSvg\(/, emA) + 1;
const lesA = at(/^\/\* ===== LESSONS:/);
const lesB = at(/^\/\* ---------- helpers ---------- \*\//, lesA);
const obA = at(/^const OB_SECS=/);
const obB = at(/^const obSrc=/, obA);
const ob2A = at(/^\/\* ---- what is kept:/, obB);
const ob2B = at(/^function obTool\(/, ob2A);
const icoA = at(/^const ICO=\{/);
const icoB = at(/^\};/, icoA) + 1;

const parts = [
  ['logic: data model, counting, run saves, step down, points, badges, quests, rhythm', slice(logicA, logicB)],
  ['emblem: the flame spirit, drawn as an SVG string', slice(emA, emB)],
  ['lessons: the 32 lessons and their sources', slice(lesA, lesB)],
  ['onboarding: the setup answers and the self-check', slice(obA, obB) + '\n' + slice(ob2A, ob2B)],
  ['icons: the line icons, as the inside of a 24 by 24 SVG (stroke, no fill)', slice(icoA, icoB)],
];

/* single declarations picked by name from anywhere in the script: the data and pure helpers behind SOS, the tools, and Rekindle.
   Each must be pure (no Store, no DOM); the extractor checks that the result runs on its own. */
const PICK = [
  // SOS
  'UR_STR', 'UR_STR_NAME', 'UR_STR_ADJ', 'UR_DID', 'UR_META', 'UR_FIT', 'UR_STRN', 'UR_PREF', 'UR_TRIG_PH', 'UR_BED_WITH', 'UR_DO', 'UR_KNOW',
  'UR_LPREF', 'UR_TR_T', 'urRate', 'urLift', 'urMinText',
  // the tools
  'TOOL_GROUPS', 'TOOLS', 'PATTERNS', 'PH_TXT', 'breathPhase', 'DONE_MSG', 'PAUSE_MS',
  'CU_BODY', 'CU_FEEL', 'CU_WHERE', 'CU_CHG', 'CU_SAY', 'CU_MS', 'CU_D',
  'GROUND', 'NEEDS', 'MOVES', 'MOVE_MS', 'FWD_A', 'FWD_B', 'THOUGHTS', 'thoughtIn', 'BED', 'TEXTS', 'FREE_LINES',
  // my reasons
  'RCATS', 'reasonGuess', 'reasonCat', 'cleanReason', 'sameReason',
  // the day and the lessons
  'STOP_IC', 'STOP_WHEN', 'HX_NEXT', 'CHEERS', 'LX_E', 'LCHECK_N', 'LCHECKS', 'LIST_OF', 'slipClean',
];
const script = html.slice(html.indexOf('<script>') + 8, html.lastIndexOf('</script>'));
const full = acorn.parse(script, { ecmaVersion: 'latest', sourceType: 'script' });
const found = new Map();
for (const node of full.body) {
  const names = node.type === 'FunctionDeclaration' ? [node.id.name] : node.type === 'VariableDeclaration' ? node.declarations.map((d) => d.id.name) : [];
  for (const n of names) if (PICK.includes(n)) found.set(n, node);
}
const missing = PICK.filter((n) => !found.has(n));
if (missing.length) throw new Error('not found in legacy/index.html: ' + missing.join(', '));
/* one statement can declare several names (const a=1,b=2); each statement is copied once, in file order */
const stmts = [...new Set(PICK.map((n) => found.get(n)))].sort((a, b) => a.start - b.start);
parts.push(['picked: the data and pure helpers behind SOS, the tools, the day and the lessons', stmts.map((n) => script.slice(n.start, n.end)).join('\n')]);

let body = parts.map(([name, src]) => `/* ------------------------------------------------------------------------------------------------\n   ${name}\n   ------------------------------------------------------------------------------------------------ */\n${src}`).join('\n\n');

/* every top-level name, exported as is */
const ast = acorn.parse(body, { ecmaVersion: 'latest', sourceType: 'script' });
const names = [];
for (const node of ast.body) {
  if (node.type === 'FunctionDeclaration') names.push(node.id.name);
  else if (node.type === 'VariableDeclaration') for (const d of node.declarations) {
    if (d.id.type === 'Identifier') names.push(d.id.name);
  }
}

const header = `/* GENERATED by tools/extract-legacy.mjs from legacy/index.html. Do not edit by hand: change the legacy file (or port the
   function to TypeScript in packages/core/src) and run \`npm run extract\`. */
/* eslint-disable */
// @ts-nocheck
`;
const out = `${header}\n${body}\n\nexport {\n${names.map((n) => '  ' + n).join(',\n')}\n};\n`;
writeFileSync(join(root, 'packages/core/src/legacy/core.js'), out);
console.log(`core.js: ${out.split('\n').length} lines, ${names.length} exports`);
